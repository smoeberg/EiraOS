#!/usr/bin/env python3
"""The app/ files the Ubuntu package installs (debian/rules reads the list).

The package used to copy all of app/ (`cp -a app`), including the
development HTTP bridge, its routers and prototype daemons. Now it installs
exactly the import closure of the production entry points: the daemons in
packaging/daemon-policy.json and the commands in packaging/bin. The closure
is computed from every `import app...` / `from app... import` in the source,
including imports inside functions, so it over-approximates rather than
misses a module.

    scripts/app_modules.py            print the closure
    scripts/app_modules.py --write    write packaging/app-modules.txt

tests/test_deb_app_modules.py fails if the file and the closure differ, so
a new import cannot be forgotten and a dev-only module cannot slip in.
"""

from __future__ import annotations

import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIST = ROOT / "packaging" / "app-modules.txt"

# Modules started by packaging/bin/* (python3 -m ...).
COMMAND_MODULES = (
    "app.daemons.runner",
    "app.gate.audit_seal",
    "app.gate.audit_verify",
    "app.rights.enroll",
    "app.rights.agent",
    "app.model.daemon",
)
# Data files read at runtime, next to the modules that load them.
DATA_FILES = (
    "app/gate/edp-1.0.schema.json",
    "app/rights/eira-rights-set-1.0.schema.json",
)
# Never in the package (tests/test_no_http_bridge_prod.py, daemon-policy.json).
FORBIDDEN_PREFIXES = ("app.http_bridge", "app.main", "app.routers")


def _policy() -> dict:
    return json.loads((ROOT / "packaging" / "daemon-policy.json").read_text())


def _module_file(module: str) -> Path | None:
    base = ROOT.joinpath(*module.split("."))
    if base.with_suffix(".py").is_file():
        return base.with_suffix(".py")
    if (base / "__init__.py").is_file():
        return base / "__init__.py"
    return None


def _imports(path: Path, module: str) -> set[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    package = module if path.name == "__init__.py" else module.rpartition(".")[0]
    found: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                parts = package.split(".")
                base = ".".join(parts[: len(parts) - node.level + 1])
                target = f"{base}.{node.module}" if node.module else base
            else:
                target = node.module or ""
            found.add(target)
            # `from app.x import y` may name a submodule y.
            found.update(f"{target}.{alias.name}" for alias in node.names)
    return {name for name in found if name == "app" or name.startswith("app.")}


def closure() -> list[str]:
    policy = _policy()
    prototypes = {f"app.daemons.{name}" for name in policy["prototype_daemons"]}
    roots = list(COMMAND_MODULES) + [f"app.daemons.{d}" for d in policy["production_daemons"]]
    seen: set[str] = set()
    files: set[Path] = set()
    queue = list(roots)
    while queue:
        module = queue.pop()
        if module in seen or module in prototypes:
            continue
        seen.add(module)
        path = _module_file(module)
        if path is None:
            continue  # a name imported from a module, not a module
        files.add(path)
        # Every package on the way needs its __init__.py.
        parts = module.split(".")
        for i in range(1, len(parts)):
            init = ROOT.joinpath(*parts[:i], "__init__.py")
            if init.is_file():
                files.add(init)
                queue.append(".".join(parts[:i]))
        queue.extend(_imports(path, module))
    for data in DATA_FILES:
        files.add(ROOT / data)
    return sorted(str(path.relative_to(ROOT)) for path in files)


def main(argv: list[str]) -> int:
    modules = closure()
    bad = [m for m in modules if m.replace("/", ".").startswith(FORBIDDEN_PREFIXES)]
    if bad:
        print(f"forbidden in the package: {bad}", file=sys.stderr)
        return 1
    if "--write" in argv:
        LIST.write_text(
            "# Generated by scripts/app_modules.py --write. Do not edit by hand.\n"
            + "\n".join(modules)
            + "\n",
            encoding="utf-8",
        )
    else:
        print("\n".join(modules))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
