"""The device's signing key, made in the TPM (EIRA-CONTEXT §5.0,
FLEET-RIGHTS-API §8 step 1, invariant A-1).

The key pair is generated inside the TPM with ``fixedTPM`` and
``fixedParent``: the private key never leaves it and cannot be duplicated to
another TPM. On disk lies only the TPM's wrapped blob (``TSS2 PRIVATE KEY``),
which is useless without this TPM. A cloned disk therefore cannot sign a
CSR, a manifest or a TLS handshake.

The work is done by OpenSSL 3 with the ``tpm2`` provider (package
``tpm2-openssl``), so the same blob is used by ``openssl`` here and by
Python's ``ssl`` for mTLS (transport.py), once OpenSSL loads the provider
through ``OPENSSL_CONF`` (``packaging/rights/openssl-tpm2.cnf``).

The TPM is reached through the resource manager ``/dev/tpmrm0``. Tests use
``swtpm`` by setting ``TPM2OPENSSL_TCTI`` (e.g. ``swtpm:port=2321``).
"""

from __future__ import annotations

import base64
import os
import subprocess
from pathlib import Path

OPENSSL = os.environ.get("EIRA_OPENSSL", "openssl")
PROVIDERS = ["-provider", "tpm2", "-provider", "default"]
TPM_DEVICE = Path("/dev/tpmrm0")
TSS2_HEADER = b"-----BEGIN TSS2 PRIVATE KEY-----"
REQUIRED_ATTRIBUTES = frozenset({"fixedTPM", "fixedParent", "sensitiveDataOrigin"})


class NoTpm(Exception):
    """The device has no TPM 2.0. Managed requires one (FLEET-RIGHTS-API §6 pt. 1a)."""


class DeviceKeyError(Exception):
    pass


def tpm_present() -> bool:
    return bool(os.environ.get("TPM2OPENSSL_TCTI")) or TPM_DEVICE.exists()


def _openssl(*args: str, stdin: bytes | None = None) -> bytes:
    try:
        result = subprocess.run([OPENSSL, *args], input=stdin, capture_output=True, check=False, timeout=60)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise DeviceKeyError(f"openssl {args[0]}: {exc}") from None
    if result.returncode != 0:
        detail = result.stderr.decode(errors="replace").strip().splitlines()
        raise DeviceKeyError(f"openssl {args[0]} failed: {detail[-1] if detail else result.returncode}")
    return result.stdout


def create(path: Path) -> None:
    """Generate a P-256 key in the TPM and write its wrapped blob to ``path``
    (mode 0600; the caller sets the final owner and mode). Refuses to leave
    anything behind that is not a non-exportable TPM key."""
    if not tpm_present():
        raise NoTpm("this device has no TPM 2.0; managed requires one")
    path.unlink(missing_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    os.close(fd)
    try:
        # The key must be generated by the tpm2 provider. With both providers
        # loaded (OPENSSL_CONF, as installed) OpenSSL may otherwise pick the
        # default provider and write a software key.
        _openssl("genpkey", *PROVIDERS, "-propquery", "?provider=tpm2", "-algorithm", "EC",
                 "-pkeyopt", "group:P-256", "-out", str(path))
        if not path.read_bytes().startswith(TSS2_HEADER):
            raise DeviceKeyError("the key was not made in the TPM")
        missing = REQUIRED_ATTRIBUTES - attributes(path)
        if missing:
            raise DeviceKeyError(f"the TPM key can be exported (missing {', '.join(sorted(missing))})")
    except BaseException:
        path.unlink(missing_ok=True)
        raise


def attributes(path: Path) -> set[str]:
    """The TPM object attributes of the key, e.g. {"fixedTPM", "fixedParent", ...}."""
    text = _openssl("pkey", *PROVIDERS, "-in", str(path), "-text", "-noout").decode(errors="replace")
    lines = text.splitlines()
    try:
        start = next(i for i, line in enumerate(lines) if line.strip() == "Object Attributes:")
    except StopIteration:
        return set()
    found = set()
    for line in lines[start + 1:]:
        if not line.startswith("  ") or ":" in line:
            break
        found.add(line.strip())
    return found


def csr(path: Path, common_name: str) -> bytes:
    """A PEM certificate signing request, signed by the TPM."""
    name = "".join(c for c in common_name if c.isalnum() or c in "-.")[:64] or "eira"
    der = _openssl("req", *PROVIDERS, "-new", "-key", str(path), "-subj", f"/CN={name}", "-sha256",
                   "-outform", "DER")
    body = base64.encodebytes(_without_null_parameters(der)).replace(b"\n", b"")
    lines = [body[i:i + 64] for i in range(0, len(body), 64)]
    return b"-----BEGIN CERTIFICATE REQUEST-----\n" + b"\n".join(lines) + b"\n-----END CERTIFICATE REQUEST-----\n"


# ecdsa-with-SHA256 with and without a NULL parameter. tpm2-openssl 1.2
# writes the NULL; RFC 5758 §3.2 says it MUST be absent, and strict parsers
# (Python cryptography, so possibly Fleet) refuse the CSR. The signature
# covers only CertificationRequestInfo, so dropping it keeps it valid.
_ECDSA_SHA256_OID = bytes.fromhex("06082a8648ce3d040302")
_ALG_WITH_NULL = b"\x30\x0c" + _ECDSA_SHA256_OID + b"\x05\x00"
_ALG = b"\x30\x0a" + _ECDSA_SHA256_OID


def _tlv(data: bytes, offset: int) -> tuple[int, int]:
    """(start of content, end) of the DER element at offset."""
    length = data[offset + 1]
    start = offset + 2
    if length & 0x80:
        count = length & 0x7F
        length = int.from_bytes(data[start:start + count], "big")
        start += count
    return start, start + length


def _der_length(n: int) -> bytes:
    if n < 0x80:
        return bytes([n])
    raw = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([0x80 | len(raw)]) + raw


def _without_null_parameters(der: bytes) -> bytes:
    start, end = _tlv(der, 0)
    if der[0] != 0x30 or end != len(der):
        raise DeviceKeyError("openssl req did not return a CSR")
    _info_start, info_end = _tlv(der, start)
    if der[info_end:info_end + len(_ALG_WITH_NULL)] != _ALG_WITH_NULL:
        return der
    content = der[start:info_end] + _ALG + der[info_end + len(_ALG_WITH_NULL):end]
    return b"\x30" + _der_length(len(content)) + content


def public_key_der(path: Path) -> bytes:
    """SubjectPublicKeyInfo (DER) of the key."""
    return _openssl("pkey", *PROVIDERS, "-in", str(path), "-pubout", "-outform", "DER")
